"""Phase 10 — Claims registry.

Renders every registered claim in outputs/claims.yaml from the metric files, so no
sentence on the site carries a typed-in number. Fails loudly if a claim references a
metric that does not exist. Also renders the resume bullet drafts.

The resume bullets reference validation_report.json, which is produced after this step;
if it is not there yet, those bullets are rendered on the next run (make all runs
claims again after validate).
"""

from __future__ import annotations

import re
from functools import lru_cache

import pandas as pd
import yaml

from src.common import path, read_json, write_json


class MissingMetric(KeyError):
    pass


@lru_cache(maxsize=None)
def _load(source: str):
    p = path("outputs") / source
    if not p.exists():
        raise MissingMetric(f"source file {source} not found")
    if source.endswith(".json"):
        return read_json(p)
    if source.endswith(".csv"):
        return pd.read_csv(p)
    raise MissingMetric(f"unsupported source {source}")


def resolve(ref: dict):
    """Return the raw value a metric reference points to."""
    data = _load(ref["source"])
    if isinstance(data, pd.DataFrame):
        df = data
        for k, v in (ref.get("where") or {}).items():
            df = df[df[k].astype(str) == str(v)]
        if ref.get("count"):
            return int(len(df))
        if df.empty:
            raise MissingMetric(f"no rows in {ref['source']} for {ref.get('where')}")
        if "pick" in ref:
            df = df.sort_values(ref["by"], ascending=ref["pick"] == "min", kind="mergesort")
        elif len(df) != 1:
            raise MissingMetric(f"{len(df)} rows match {ref.get('where')} in {ref['source']}")
        if ref["field"] not in df.columns:
            raise MissingMetric(f"column {ref['field']} not in {ref['source']}")
        v = df.iloc[0][ref["field"]]
        return v.item() if hasattr(v, "item") else v
    node = data
    for part in ref["path"].split("."):
        if not isinstance(node, dict) or part not in node or node[part] is None:
            raise MissingMetric(f"{ref['source']}:{ref['path']} missing")
        node = node[part]
    return len(node) if ref.get("length") else node


def fmt(value, f: str) -> str:
    if f == "text":
        return str(value)
    v = float(value)
    return {
        "pct0": lambda: f"{v * 100:.0f}%",
        "pct1": lambda: f"{v * 100:.1f}%",
        "pct2": lambda: f"{v * 100:.2f}%",
        "pp1": lambda: f"{v:.1f}pp",
        "pp2": lambda: f"{v:.2f}pp",
        "int": lambda: f"{round(v):,}",
        "num1": lambda: f"{v:.1f}",
        "num2": lambda: f"{v:.2f}",
        "num3": lambda: f"{v:.3f}",
        "x1": lambda: f"{v:.1f}×",
        "x2": lambda: f"{v:.2f}×",
        "money": lambda: f"{v:,.0f}",
    }[f]()


def render(template: str, metrics: dict) -> tuple[str, dict]:
    values = {}
    for name, ref in metrics.items():
        raw = resolve(ref)
        values[name] = {"raw": raw, "formatted": fmt(raw, ref.get("format", "text")),
                        "format": ref.get("format", "text"), "source": ref["source"]}
    missing = set(re.findall(r"{(\w+)}", template)) - set(values)
    if missing:
        raise MissingMetric(f"template placeholders without metrics: {missing}")
    return template.format(**{k: v["formatted"] for k, v in values.items()}), values


def load_registry() -> dict:
    with open(path("outputs") / "claims.yaml", encoding="utf-8") as f:
        return yaml.safe_load(f)


def main() -> dict:
    _load.cache_clear()
    reg = load_registry()
    rendered = []
    for c in reg["claims"]:
        text, values = render(c["template"], c["metrics"])
        rendered.append(
            {
                "id": c["id"],
                "group": c["group"],
                "title": c["title"],
                "text": text,
                "sources": sorted({v["source"] for v in values.values()}),
                "values": values,
            }
        )
    write_json({"claims": rendered}, path("outputs") / "claims_rendered.json")

    try:
        bullets = [render(t, reg["resume_metrics"])[0] for t in reg["resume_bullets"]]
        md = ["# Resume bullet drafts", "",
              "Generated by `src/claims.py` from the pipeline outputs. Edit the templates in "
              "`outputs/claims.yaml`, not this file.", ""]
        md += [f"- {b}" for b in bullets]
        (path("outputs") / "resume_bullets.md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    except MissingMetric as e:
        print(f"resume bullets deferred: {e}")

    for r in rendered:
        print(f"{r['id']}: {r['text']}")
    return {"claims": rendered}


if __name__ == "__main__":
    main()
